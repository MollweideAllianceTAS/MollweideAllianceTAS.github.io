#!/usr/bin/env node
/* Compile one small JSON file per airline into the classic script the site uses. */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const DIR = path.join(ROOT, 'content', 'airlines');
const OUT = path.join(ROOT, 'assets', 'js', 'members.generated.js');
const checkOnly = process.argv.includes('--check');

const fail = message => { console.error(`Content error: ${message}`); process.exitCode = 1; };
const files = fs.readdirSync(DIR).filter(file => file.endsWith('.json') && !file.startsWith('_')).sort();
const records = [];

for (const file of files) {
  let item;
  try { item = JSON.parse(fs.readFileSync(path.join(DIR, file), 'utf8')); }
  catch (error) { fail(`${file} is not valid JSON (${error.message})`); continue; }

  const required = ['name', 'code', 'country', 'color', 'tail', 'hubs', 'joined', 'blurb'];
  required.forEach(field => {
    if (item[field] === undefined || item[field] === '' || item[field] === null) fail(`${file} is missing ${field}`);
  });
  if (!/^[A-Z0-9]{2}$/.test(item.code || '')) fail(`${file}: code must be two capital letters or numbers`);
  if (!/^#[0-9A-Fa-f]{6}$/.test(item.color || '')) fail(`${file}: color must look like #13398C`);
  if (!Array.isArray(item.hubs) || !item.hubs.length) fail(`${file}: hubs must contain at least one airport code`);
  if (!Array.isArray(item.focus)) item.focus = [];
  records.push({ file, item });
}

const codes = new Map();
records.forEach(({ file, item }) => {
  if (codes.has(item.code)) fail(`${file} repeats code ${item.code} from ${codes.get(item.code)}`);
  codes.set(item.code, file);
});
if (process.exitCode) process.exit(process.exitCode);

records.sort((a, b) => (a.item.order ?? 9999) - (b.item.order ?? 9999) || a.item.name.localeCompare(b.item.name));
const airlines = records.map(({ item }) => {
  const clean = { ...item };
  delete clean.order;
  return clean;
});
const output = `/* Generated by tools/content-pipeline.js. Edit content/airlines/*.json, not this file. */\nconst MWA_MEMBERS = ${JSON.stringify(airlines, null, 2)};\n`;

if (checkOnly) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== output) fail('member content has changed; run npm run build:content');
  else console.log(`Content is current: ${airlines.length} airlines.`);
} else {
  fs.writeFileSync(OUT, output);
  console.log(`Built ${path.relative(ROOT, OUT)} from ${airlines.length} airline files.`);
}
